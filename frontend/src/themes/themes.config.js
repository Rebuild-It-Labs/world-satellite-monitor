export const DEFAULT_THEME_ID = "mission-control";

export function getThemeById(id) {
  return THEMES.find((t) => t.id === id) || THEMES[0];
}

export function getThemeAssetUrl(folder, file) {
  const base = import.meta.env.BASE_URL || "./";
  const cleanBase = base.endsWith("/") ? base : `${base}/`;
  return `${cleanBase}themes/${folder}/${file}`;
}

export function getRandomThemeQuote(theme) {
  if (!theme || !theme.quotes) return null;
  if (Array.isArray(theme.quotes.banners) && theme.quotes.banners.length > 0) {
    const idx = Math.floor(Math.random() * theme.quotes.banners.length);
    return theme.quotes.banners[idx];
  }
  return theme.quotes.banner || null;
}
